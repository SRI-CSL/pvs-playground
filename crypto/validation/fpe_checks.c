/* SP 800-38G. NIST FF1samples and FF3samples use lowercase base-36 digits. */
#include "fpe_c.h"
#include <assert.h>
#include <ctype.h>

static fpe_array_15_t octets(const char *hex) {
    uint32_t n=strlen(hex)/2;
    fpe_array_15_t a=new_fpe_array_15(n);
    for (uint32_t i=0;i<n;++i) {
        unsigned b;
        assert(sscanf(hex+2*i,"%2x",&b)==1);
        a->elems[i]=(uint8_t)b;
    }
    return a;
}
static aes_modes__mode_key_adt_t key(const char *k) {
    aes_modes_array_1_t a=(aes_modes_array_1_t)octets(k);
    if (a->size==16) return con_aes_modes__mk128(a);
    if (a->size==24) return con_aes_modes__mk192(a);
    assert(a->size==32);
    return con_aes_modes__mk256(a);
}
static fpe__tweak_string_t tweak(const char *t) {
    fpe__tweak_string_t x=new_fpe__tweak_string();
    x->seq=octets(t);
    x->length=x->seq->size;
    return x;
}
static fpe_record_2_t numeral(const char *s) {
    fpe_record_2_t x=new_fpe_record_2();
    x->length=strlen(s);
    x->digits=new_fpe_array_1(x->length);
    for (uint32_t j=0;j<x->length;++j)
        x->digits->elems[j]=isdigit((unsigned char)s[j]) ? s[j]-'0' : tolower((unsigned char)s[j])-'a'+10;
    return x;
}
static void check(bool ff3,uint32_t r,const char *k,const char *t,const char *p,const char *c) {
    for (int inverse=0;inverse<2;++inverse) {
        fpe__result_adt_t y=fpe__crypt(key(k),false,ff3,inverse,tweak(t),r,numeral(inverse?c:p));
        assert(y->fpe__result_adt_index==0);
        fpe_record_2_t actual=((fpe__encoded_t)y)->text;
        fpe_record_2_t expected=numeral(inverse?p:c);
        assert(actual->length==expected->length);
        assert(memcmp(actual->digits->elems,expected->digits->elems,expected->length*sizeof(uint16_t))==0);
        release_fpe_record_2(expected);
        release_fpe__result_adt(y);
    }
}
